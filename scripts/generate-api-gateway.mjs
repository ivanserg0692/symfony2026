#!/usr/bin/env node

import { execFileSync } from 'node:child_process';
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';

const METHOD_ORDER = ['get', 'post', 'put', 'patch', 'delete', 'options', 'head', 'trace'];
const CONFIG_PATH = 'api-gateway/routes.json';
const OPENAPI_HEADER_PATH = 'api-gateway/openapi-header.json';
const NGINX_ROUTES_OUTPUT_PATH = 'docker/nginx/snippets/generated-api-gateway-routes.conf';
const OPENAPI_OUTPUT_PATH = 'symfony/public/api-gateway/openapi.json';

function main() {
  const config = readJson(CONFIG_PATH);

  validateConfig(config);
  writeText(NGINX_ROUTES_OUTPUT_PATH, renderNginxRoutes(config));
  writeJson(OPENAPI_OUTPUT_PATH, buildGatewayOpenApi(config));
}

function validateConfig(config) {
  for (const name of ['openapiSources', 'routes']) {
    if (!config[name]) {
      throw new Error(`Missing API Gateway config section: ${name}`);
    }
  }

  const routeIds = new Set();

  for (const route of config.routes) {
    for (const name of ['id', 'match', 'publicPath', 'upstream', 'internalPath']) {
      if (!route[name]) {
        throw new Error(`Route is missing ${name}: ${JSON.stringify(route)}`);
      }
    }

    if (routeIds.has(route.id)) {
      throw new Error(`Duplicate route id: ${route.id}`);
    }

    routeIds.add(route.id);

    if (!['exact', 'prefix'].includes(route.match)) {
      throw new Error(`Unsupported match type for route ${route.id}: ${route.match}`);
    }

    if (route.openapi && !config.openapiSources[route.openapi.source]) {
      throw new Error(`Unknown OpenAPI source for route ${route.id}: ${route.openapi.source}`);
    }
  }
}

function renderNginxRoutes(config) {
  return "# This file is generated by npm run gateway:generate. Edit api-gateway/routes.json instead.\n\n"
    + config.routes.flatMap((route) => [
      renderRoute(route),
      ...(route.auth ? [renderPreflightRoute(route)] : []),
    ]).join("\n\n")
    + "\n";
}

function renderRoute(route) {
  const lines = [
    `    location ${route.match === 'exact' ? '=' : '^~'} ${route.publicPath} {`,
  ];

  if (route.auth) {
    lines.push(
      `        error_page 418 = @gateway_preflight_${sanitizeNginxName(route.id)};`,
      "        if ($request_method = OPTIONS) {",
      "            return 418;",
      "        }",
      "",
    );
    lines.push("        include /etc/nginx/snippets/auth-required.conf;", "");
  }

  if (route.publicPath !== route.internalPath) {
    lines.push(`        rewrite ^${escapeNginxRegex(route.publicPath)}(.*)$ ${route.internalPath}$1 break;`);
  }

  lines.push(`        proxy_pass http://${route.upstream};`);

  if (!route.auth) {
    lines.push('        proxy_hide_header X-User-Id;');
  }

  lines.push('', '        include /etc/nginx/snippets/proxy-common.conf;');

  if (route.auth) {
    lines.push('        include /etc/nginx/snippets/proxy-auth-user.conf;');
  } else {
    lines.push('        proxy_set_header X-User-Id "";');
  }

  lines.push('    }');

  return lines.join('\n');
}

function renderPreflightRoute(route) {
  const lines = [
    `    location @gateway_preflight_${sanitizeNginxName(route.id)} {`,
  ];

  if (route.publicPath !== route.internalPath) {
    lines.push(`        rewrite ^${escapeNginxRegex(route.publicPath)}(.*)$ ${route.internalPath}$1 break;`);
  }

  lines.push(
    `        proxy_pass http://${route.upstream};`,
    "        proxy_hide_header X-User-Id;",
    "",
    "        include /etc/nginx/snippets/proxy-common.conf;",
    "        proxy_set_header X-User-Id \"\";",
    "    }",
  );

  return lines.join("\n");
}

function buildGatewayOpenApi(config) {
  const sourceCache = new Map();
  const gateway = readOpenApiHeader();

  gateway['x-generated-by'] = 'npm run gateway:generate';
  gateway['x-source-manifest'] = CONFIG_PATH;
  gateway['x-openapi-header'] = OPENAPI_HEADER_PATH;
  gateway['x-generated-note'] = 'This file is generated automatically. Edit api-gateway/routes.json or api-gateway/openapi-header.json and rerun npm run gateway:generate.';
  gateway.paths = {};
  gateway.components ??= {};
  gateway.components.securitySchemes = {
    ...gateway.components.securitySchemes,
    bearerAuth: {
      type: 'http',
      scheme: 'bearer',
      bearerFormat: 'JWT',
    },
  };
  gateway.tags ??= [];

  const sourceNames = new Set();

  for (const route of config.routes) {
    if (!route.openapi) {
      continue;
    }

    sourceNames.add(route.openapi.source);

    const source = readOpenApiSource(route.openapi.source, config.openapiSources[route.openapi.source], sourceCache);

    for (const [sourcePath, pathItem] of Object.entries(source.paths ?? {})) {
      if (!matchesOpenApiRoute(sourcePath, route.openapi)) {
        continue;
      }

      const publicPath = translatePath(sourcePath, route);
      gateway.paths[publicPath] = mergePathItem(gateway.paths[publicPath], buildGatewayPathItem(pathItem, route));
    }
  }

  for (const sourceName of sourceNames) {
    const source = sourceCache.get(sourceName);
    mergeComponents(gateway.components, source.components ?? {}, sourceName);
    mergeTags(gateway.tags, source.tags ?? []);
  }

  gateway.paths = sortObjectByKey(gateway.paths);
  gateway.tags = filterUsedTags(gateway.tags, gateway.paths)
    .sort((left, right) => String(left.name ?? '').localeCompare(String(right.name ?? '')));

  return gateway;
}

function readOpenApiHeader() {
  const header = readJson(OPENAPI_HEADER_PATH);

  return {
    ...header,
    paths: {
      ...header.paths,
    },
    components: {
      ...header.components,
      securitySchemes: {
        ...header.components?.securitySchemes,
      },
    },
    tags: [
      ...(header.tags ?? []),
    ],
  };
}

function readOpenApiSource(name, sourceConfig, sourceCache) {
  if (!sourceCache.has(name)) {
    sourceCache.set(name, sourceConfig.sourceType === 'docker'
      ? dumpOpenApiFromService(sourceConfig.source)
      : readJson(sourceConfig.source));
  }

  return sourceCache.get(name);
}

function dumpOpenApiFromService(composeService) {
  const output = execFileSync(
    'docker',
    ['compose', 'exec', '-T', composeService, 'php', 'bin/console', 'nelmio:apidoc:dump', '--format=json'],
    {
      cwd: process.cwd(),
      encoding: 'utf8',
      stdio: ['ignore', 'pipe', 'inherit'],
    },
  );

  return JSON.parse(output);
}

function matchesOpenApiRoute(path, openapiRoute) {
  if (openapiRoute.path) {
    return path === openapiRoute.path;
  }

  if (openapiRoute.pathPrefix) {
    return path === openapiRoute.pathPrefix || path.startsWith(`${openapiRoute.pathPrefix}/`);
  }

  throw new Error(`OpenAPI route must define path or pathPrefix: ${JSON.stringify(openapiRoute)}`);
}

function translatePath(sourcePath, route) {
  if (route.publicPath === route.internalPath) {
    return sourcePath;
  }

  if (sourcePath === route.internalPath) {
    return route.publicPath;
  }

  if (!sourcePath.startsWith(`${route.internalPath}/`)) {
    throw new Error(`Cannot translate ${sourcePath} from ${route.internalPath} to ${route.publicPath}`);
  }

  return `${route.publicPath}${sourcePath.slice(route.internalPath.length)}`;
}

function buildGatewayPathItem(pathItem, route) {
  return Object.fromEntries(Object.entries(pathItem).map(([key, value]) => {
    if (!METHOD_ORDER.includes(key)) {
      return [key, value];
    }

    return [key, buildGatewayOperation(value, route)];
  }));
}

function buildGatewayOperation(operation, route) {
  const gatewayOperation = structuredClone(operation);

  if (route.auth) {
    gatewayOperation.security = [{ bearerAuth: [] }];
  }

  return gatewayOperation;
}

function mergePathItem(currentPathItem = {}, nextPathItem) {
  const merged = { ...currentPathItem };

  for (const [key, value] of Object.entries(nextPathItem)) {
    if (merged[key] && JSON.stringify(merged[key]) !== JSON.stringify(value)) {
      throw new Error(`Conflicting OpenAPI path item entry: ${key}`);
    }

    merged[key] = value;
  }

  return sortPathItem(merged);
}

function sortPathItem(pathItem) {
  const sorted = {};

  for (const key of [...METHOD_ORDER, 'parameters']) {
    if (pathItem[key]) {
      sorted[key] = pathItem[key];
    }
  }

  for (const key of Object.keys(pathItem).sort()) {
    if (!sorted[key]) {
      sorted[key] = pathItem[key];
    }
  }

  return sorted;
}

function mergeComponents(targetComponents, sourceComponents, sourceName) {
  for (const [componentType, components] of Object.entries(sourceComponents)) {
    targetComponents[componentType] ??= {};

    for (const [name, value] of Object.entries(components ?? {})) {
      if (componentType === 'securitySchemes' && targetComponents[componentType][name]) {
        continue;
      }

      if (targetComponents[componentType][name] && JSON.stringify(targetComponents[componentType][name]) !== JSON.stringify(value)) {
        throw new Error(`Conflicting OpenAPI component ${componentType}.${name} from source ${sourceName}`);
      }

      targetComponents[componentType][name] = value;
    }

    targetComponents[componentType] = sortObjectByKey(targetComponents[componentType]);
  }
}

function mergeTags(targetTags, sourceTags) {
  const existing = new Set(targetTags.map((tag) => tag.name));

  for (const tag of sourceTags) {
    if (!tag.name || existing.has(tag.name)) {
      continue;
    }

    targetTags.push(tag);
    existing.add(tag.name);
  }
}

function filterUsedTags(tags, paths) {
  const usedTags = collectUsedTags(paths);

  return tags.filter((tag) => tag.name && usedTags.has(tag.name));
}

function collectUsedTags(paths) {
  const usedTags = new Set();

  for (const pathItem of Object.values(paths)) {
    for (const [key, operation] of Object.entries(pathItem)) {
      if (!METHOD_ORDER.includes(key)) {
        continue;
      }

      for (const tagName of operation.tags ?? []) {
        usedTags.add(tagName);
      }
    }
  }

  return usedTags;
}

function sortObjectByKey(object) {
  return Object.fromEntries(Object.entries(object).sort(([left], [right]) => left.localeCompare(right)));
}

function escapeNginxRegex(value) {
  return value.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
}

function sanitizeNginxName(value) {
  return value.replace(/[^A-Za-z0-9_]/g, "_");
}

function readJson(path) {
  return JSON.parse(readFileSync(resolve(process.cwd(), path), 'utf8'));
}

function writeText(path, content) {
  const absolutePath = resolve(process.cwd(), path);

  mkdirSync(dirname(absolutePath), { recursive: true });
  writeFileSync(absolutePath, content);
}

function writeJson(path, data) {
  writeText(path, `${JSON.stringify(data, null, 2)}\n`);
}

main();
